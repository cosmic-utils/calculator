#[derive(Debug, Clone, PartialEq)]
pub enum Operator {
    Add,
    Subtract,
    Multiply,
    Divide,
    Modulus,
    Point,
    Equal,
    Clear,
    ClearEntry,
    Backspace,
    Negate,
    ParenthesesOpen,
    ParenthesesClose,
    Power,
    SquareRoot,
    // Scientific
    Comma,
    Log,
    Ln,
    Log2,
    Factorial,
    Sin,
    Cos,
    Tan,
    Asin,
    Acos,
    Atan,
    Pi,
    E,
    Reciprocal,
    Sinh,
    Cosh,
    Tanh,
    Degree,
    Square,
    Cube,
    PowerOfTen,
    Exp,
    Abs,
    CubeRoot,
    // Statistics
    Sum,
    Mean,
    Median,
    Mode,
    Min,
    Max,
    StdDev,
    StdDevPopulation,
    Variance,
    VariancePopulation,
    Combinations,
    Permutations,
}

impl Operator {
    pub fn display(&self, decimal_comma: bool) -> &str {
        match self {
            Self::Add => "+",
            Self::Subtract => "-",
            Self::Multiply => "x",
            Self::Divide => "÷",
            Self::Modulus => "%",
            Self::Point => if decimal_comma {","} else {"."},
            Self::Equal => "=",
            Self::ParenthesesOpen => "(",
            Self::ParenthesesClose => ")",
            Self::Power => "^",
            Self::SquareRoot => "√",
            Self::Clear => "C",
            Self::ClearEntry => "CE",
            Self::Backspace => "⌫",
            Self::Negate => "±",
            // Scientific
            Self::Comma => if decimal_comma {";"} else {","},
            Self::Log => "log",
            Self::Ln => "ln",
            Self::Log2 => "log2",
            Self::Factorial => "!",
            Self::Sin => "sin",
            Self::Cos => "cos",
            Self::Tan => "tan",
            Self::Asin => "asin",
            Self::Acos => "acos",
            Self::Atan => "atan",
            Self::Pi => "π",
            Self::E => "e",
            Self::Reciprocal => "1/x",
            Self::Sinh => "sinh",
            Self::Cosh => "cosh",
            Self::Tanh => "tanh",
            Self::Degree => "°",
            Self::Square => "x²",
            Self::Cube => "x³",
            Self::PowerOfTen => "10ˣ",
            Self::Exp => "eˣ",
            Self::Abs => "|x|",
            Self::CubeRoot => "∛",
            // Statistics
            Self::Sum => "Σ",
            Self::Mean => "mean",
            Self::Median => "median",
            Self::Mode => "mode",
            Self::Min => "min",
            Self::Max => "max",
            Self::StdDev => "stdev",
            Self::StdDevPopulation => "stdevp",
            Self::Variance => "var",
            Self::VariancePopulation => "varp",
            Self::Combinations => "nCr",
            Self::Permutations => "nPr",
        }
    }

    pub fn expression(&self, decimal_comma: bool) -> &str {
        match self {
            Self::Add => "+",
            Self::Subtract => "-",
            Self::Multiply => "*",
            Self::Divide => "/",
            Self::Modulus => "%",
            Self::Point => if decimal_comma {","} else {"."},
            Self::Equal => "=",
            Self::ParenthesesOpen => "(",
            Self::ParenthesesClose => ")",
            Self::Power => "^",
            Self::SquareRoot => "√",
            Self::Clear => "C",
            Self::ClearEntry => "CE",
            Self::Backspace => "⌫",
            Self::Negate => "±",
            Self::Comma => if decimal_comma {";"} else {","},
            Self::Log => "log10(",
            Self::Ln => "ln",
            Self::Log2 => "log2(",
            Self::Factorial => "!",
            Self::Sin => "sin",
            Self::Cos => "cos",
            Self::Tan => "tan",
            Self::Asin => "asin",
            Self::Acos => "acos",
            Self::Atan => "atan",
            Self::Pi => "π",
            Self::E => "e",
            Self::Reciprocal => "⁻¹",
            Self::Sinh => "sinh",
            Self::Cosh => "cosh",
            Self::Tanh => "tanh",
            Self::Degree => "°",
            Self::Square => "^2",
            Self::Cube => "^3",
            // Function forms multiply implicitly after a number, unlike `10^`.
            Self::PowerOfTen => "exp10(",
            Self::Exp => "exp(",
            Self::Abs => "abs(",
            Self::CubeRoot => "cbrt(",
            // Statistics: qalc takes the data as arguments, e.g. mean(1, 2, 3).
            Self::Sum => "total(",
            Self::Mean => "mean(",
            Self::Median => "median(",
            Self::Mode => "mode(",
            Self::Min => "min(",
            Self::Max => "max(",
            Self::StdDev => "stdev(",
            Self::StdDevPopulation => "stdevp(",
            Self::Variance => "var(",
            Self::VariancePopulation => "varp(",
            Self::Combinations => "comb(",
            Self::Permutations => "perm(",
        }
    }
}